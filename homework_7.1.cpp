#include <iostream>

using namespace std;


class NegativeNumberExpection : public runtime_error {
public:
	NegativeNumberExpection(string message) : runtime_error(message){}
};

void division(int n1, int n2){
	if (n2 == 0){
		throw invalid_argument("Value can`t = 0!");
	}else if(n1 < 0 || n2 < 0){
		throw NegativeNumberExpection("The program can`t work with negative numbers!");
	}


	else {
		cout << n1 << " / " << n2 << " = " << n1 / n2 << endl;
	}
}

